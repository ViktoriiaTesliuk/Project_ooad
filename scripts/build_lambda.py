#!/usr/bin/env python3
"""Build a reproducible AWS Lambda deployment package for Pocket Ledger.

    python scripts/build_lambda.py                 # dist/pocket-ledger-lambda-arm64.zip
    python scripts/build_lambda.py --arch x86_64
    python scripts/build_lambda.py --lock          # refresh requirements-lambda.txt

The package targets the Lambda ``python3.13`` runtime. Dependencies come from
``requirements-lambda.txt``: exact versions with sha256 hashes for both Lambda
architectures, installed as prebuilt Linux wheels. The zip has sorted entries,
fixed timestamps and permissions, and no host-specific files, so the same
lock file and sources produce the same archive on any machine.

Nothing is uploaded; deploy the zip from the AWS Console (see README).
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements-lambda.txt"
PYTHON_VERSION = "3.13"
PLATFORMS = {
    "arm64": ("manylinux_2_28_aarch64", "manylinux_2_17_aarch64", "manylinux2014_aarch64"),
    "x86_64": ("manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64"),
}
FIXED_TIME = (1980, 1, 1, 0, 0, 0)
SOURCES = ("pocket_ledger", "migrations")
REQUIRED = (
    "pocket_ledger/__init__.py",
    "pocket_ledger/lambda_handler.py",
    "pocket_ledger/templates/base.html",
    "pocket_ledger/templates/dashboard.html",
    "pocket_ledger/templates/csv_import.html",
    "pocket_ledger/templates/error.html",
    "pocket_ledger/static/app.css",
    "pocket_ledger/static/icon.svg",
    "pocket_ledger/static/sample-transactions.csv",
    "migrations/001_initial.sql",
    "flask/__init__.py",
    "authlib/__init__.py",
    "joserfc/__init__.py",
    "boto3/__init__.py",
    "requests/__init__.py",
    "sqlparse/__init__.py",
    "dotenv/__init__.py",
)
FORBIDDEN_NAMES = {".env", ".DS_Store"}
ZIP_LIMIT = 50 * 1024 * 1024  # direct upload in the Lambda console
UNZIPPED_LIMIT = 250 * 1024 * 1024


def pip(*args):
    command = [sys.executable, "-m", "pip", "--disable-pip-version-check", "--no-input", *args]
    subprocess.run(command, check=True)


def platform_args(arch):
    args = ["--python-version", PYTHON_VERSION, "--implementation", "cp", "--only-binary=:all:"]
    for tag in PLATFORMS[arch]:
        args += ["--platform", tag]
    return args


def lock():
    """Resolve requirements.txt for both architectures and record hashes."""
    resolved = {}
    with tempfile.TemporaryDirectory() as tmp:
        for arch in PLATFORMS:
            report = Path(tmp) / f"{arch}.json"
            pip("install", "--quiet", "--dry-run", "--ignore-installed", "--report", str(report),
                "-r", str(ROOT / "requirements.txt"), *platform_args(arch))
            for item in json.loads(report.read_text())["install"]:
                name = item["metadata"]["name"].lower().replace("_", "-")
                version = item["metadata"]["version"]
                digest = item["download_info"]["archive_info"]["hashes"]["sha256"]
                previous = resolved.setdefault(name, (version, set()))
                if previous[0] != version:
                    raise SystemExit(f"{name} resolves to {previous[0]} and {version} on different architectures")
                previous[1].add(digest)
    lines = [
        "# Generated by scripts/build_lambda.py --lock for the Lambda python3.13 runtime",
        "# (arm64 and x86_64 manylinux wheels). Do not edit by hand.",
    ]
    for name in sorted(resolved):
        version, digests = resolved[name]
        lines.append(f"{name}=={version} \\")
        lines.extend(f"    --hash=sha256:{d}" + (" \\" if i < len(digests) - 1 else "")
                     for i, d in enumerate(sorted(digests)))
    LOCK.write_text("\n".join(lines) + "\n")
    print(f"Wrote {LOCK.relative_to(ROOT)} with {len(resolved)} packages.")


def install_dependencies(target, arch):
    if not LOCK.exists():
        raise SystemExit("requirements-lambda.txt is missing. Run with --lock first.")
    pip("install", "--quiet", "--no-deps", "--require-hashes", "--no-compile",
        "--target", str(target), "-r", str(LOCK), *platform_args(arch))
    # Console scripts embed the build machine's interpreter path; RECORD lists
    # their hashes. Neither is needed at runtime.
    shutil.rmtree(target / "bin", ignore_errors=True)
    for dist_info in target.glob("*.dist-info"):
        for name in ("RECORD", "INSTALLER", "REQUESTED", "direct_url.json"):
            (dist_info / name).unlink(missing_ok=True)


def copy_sources(target):
    for name in SOURCES:
        shutil.copytree(
            ROOT / name, target / name,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"),
        )


def write_zip(source, destination):
    files = sorted(p for p in source.rglob("*") if p.is_file())
    destination.parent.mkdir(parents=True, exist_ok=True)
    unzipped = 0
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in files:
            relative = path.relative_to(source).as_posix()
            info = zipfile.ZipInfo(relative, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            info.create_system = 3
            data = path.read_bytes()
            unzipped += len(data)
            archive.writestr(info, data, compresslevel=9)
    return unzipped


def check_contents(archive_path, arch):
    with zipfile.ZipFile(archive_path) as archive:
        names = set(archive.namelist())
    missing = [name for name in REQUIRED if name not in names]
    forbidden = sorted(n for n in names if Path(n).name in FORBIDDEN_NAMES or "__pycache__" in n)
    machine = "aarch64" if arch == "arm64" else "x86_64"
    native = [n for n in names if n.startswith("cryptography/hazmat/bindings/") and n.endswith(".so")]
    problems = []
    if missing:
        problems.append("missing: " + ", ".join(missing))
    if forbidden:
        problems.append("must not be packaged: " + ", ".join(forbidden))
    if not native:
        problems.append("cryptography's native extension is missing")
    if problems:
        raise SystemExit("Package check failed: " + "; ".join(problems))
    templates = sorted(n for n in names if n.startswith("pocket_ledger/templates/"))
    static = sorted(n for n in names if n.startswith("pocket_ledger/static/"))
    print(f"Contents OK: {len(templates)} templates, {len(static)} static files, "
          f"{len([n for n in names if n.startswith('migrations/')])} migrations, "
          f"native extensions for {machine}.")


def build(arch, output):
    with tempfile.TemporaryDirectory() as tmp:
        staging = Path(tmp) / "package"
        staging.mkdir()
        install_dependencies(staging, arch)
        copy_sources(staging)
        unzipped = write_zip(staging, output)
    check_contents(output, arch)
    size = output.stat().st_size
    if size > ZIP_LIMIT or unzipped > UNZIPPED_LIMIT:
        raise SystemExit(f"Package too large: {size} bytes zipped, {unzipped} unzipped")
    digest = hashlib.sha256(output.read_bytes()).hexdigest()
    print(f"Built {output.relative_to(ROOT)} for {arch}: {size / 1e6:.1f} MB zipped, "
          f"{unzipped / 1e6:.1f} MB unzipped")
    print(f"sha256 {digest}")
    return digest


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--arch", choices=sorted(PLATFORMS), default="arm64")
    parser.add_argument("--lock", action="store_true", help="refresh requirements-lambda.txt and exit")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.lock:
        lock()
        return
    os.environ.setdefault("PIP_NO_CACHE_DIR", "0")
    output = args.output or ROOT / "dist" / f"pocket-ledger-lambda-{args.arch}.zip"
    build(args.arch, output.resolve())


if __name__ == "__main__":
    main()
